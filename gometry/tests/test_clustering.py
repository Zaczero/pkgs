    points = gm.points(xs, ys)
    x_view = np.asarray(points.coords.x)
    assert x_view.dtype == np.float64
    assert not x_view.flags.owndata and (not x_view.flags.writeable)
    y_view = np.asarray(points.coords.y)
    assert y_view.dtype == np.float64
    assert not y_view.flags.owndata and (not y_view.flags.writeable)
    coords = np.column_stack((x_view, y_view))
    assert coords.shape == (60, 2)
    model = sklearn_cluster.KMeans(n_clusters=3, n_init=1, random_state=0)
    labels = [int(label) for label in model.fit(coords).labels_]
    assert len(set(labels)) == 3
    merged, groups = points.dissolve(by=labels)
    assert len(merged) == 3 and len(groups) == 3
    parcels = gm.GeometryArray([gm.box(x, 0, x + 1, 1) for x in (0.0, 1.2, 50.0)])
    centroids = (parcels).centroid().coords
    centroid_x = np.asarray(centroids.x)
    centroid_y = np.asarray(centroids.y)
    assert centroid_x.dtype == np.float64
    assert centroid_y.dtype == np.float64
    assert not centroid_x.flags.owndata and (not centroid_x.flags.writeable)
    assert not centroid_y.flags.owndata and (not centroid_y.flags.writeable)
    centers = np.column_stack((centroid_x, centroid_y))
    assert centers.shape == (3, 2)
    dbscan = sklearn_cluster.DBSCAN(eps=2.0, min_samples=1).fit(centers)
    assert list(dbscan.labels_) == [0, 0, 1]
