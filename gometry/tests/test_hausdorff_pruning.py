def _assert_tolerance(actual: float, expected: float, key: str) -> None:
    if math.isinf(expected):
        assert math.isinf(actual)
        return
    tol = 1e-09 * max(1.0, abs(expected))
    assert abs(actual - expected) <= tol, (
        f'{key}: expected {expected} got {actual} (tol {tol})'
    )


