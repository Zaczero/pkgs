const fn pack_encode_table(source: &[(usize, u64); 257]) -> [u64; 257] {
    let mut packed = [0; 257];
    let mut index = 0;
    while index < source.len() {
        let (code_bits, code) = source[index];
        assert!(code_bits <= 30);
        assert!(code <= u32::MAX as u64);
        packed[index] = code | ((code_bits as u64) << 32);
        index += 1;
    }
    packed
}
