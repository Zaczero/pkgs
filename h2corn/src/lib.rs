// Sanitizers must observe allocation lifetimes and allocator synchronization.
#[cfg(not(any(miri, sanitize = "address", sanitize = "thread")))]
#[global_allocator]
static GLOBAL_ALLOCATOR: mimalloc::MiMalloc = mimalloc::MiMalloc;

#[cfg(any(miri, sanitize = "address", sanitize = "thread"))]
use mimalloc as _;
use pyo3::prelude::*;

#[pymodule]
#[pyo3(name = "_lib")]
fn init_lib_module(m: &Bound<'_, PyModule>) -> PyResult<()> {
    m.add_class::<pyapi::PreparedTls>()?;
    m.add_function(wrap_pyfunction!(pyapi::prepare_tls, m)?)?;
    m.add_function(wrap_pyfunction!(pyapi::emit_banner, m)?)?;
    m.add_function(wrap_pyfunction!(pyapi::serve_fds, m)?)?;
    Ok(())
}
